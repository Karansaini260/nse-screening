# ---------------------------------------------------------------------------
# Intent matchers
# ---------------------------------------------------------------------------
_SYMBOL_PATTERN = r"\b([A-Z][A-Z0-9&\-]{2,15})\b"  # RELIANCE, M&M, BAJAJ-AUTO, etc.
_VALID_SYMBOLS = set(wsc.NIFTY_100_SYMBOLS)


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


def _find_symbol(text: str) -> Optional[str]:
    """Return the Nifty 100 symbol mentioned in the text, if any.

    Match case-insensitively so 'price reliance' and 'Price RELIANCE'
    both work, but only accept the candidate if it's a real Nifty 100
    symbol — this prevents common English words (e.g. 'top', 'ltp')
    from being mistaken for tickers.
    """
    for m in re.finditer(_SYMBOL_PATTERN, text, re.IGNORECASE):
        candidate = m.group(1).upper()
        if candidate in _VALID_SYMBOLS:
            return candidate
    return None


def _glossary(term: str) -> Optional[str]:
    term = term.lower().strip()
    if term in GLOSSARY:
        return GLOSSARY[term]
    # Fuzzy match against keys so "smma 20" still finds "smma".
    keys = list(GLOSSARY.keys())
    matches = difflib.get_close_matches(term, keys, n=1, cutoff=0.6)
    if matches:
        return GLOSSARY[matches[0]]
    return None


def _fuzzy_faq(question: str) -> Optional[str]:
    q = _norm(question)
    if not q:
        return None
    questions = [f[0] for f in FAQS]
    matches = difflib.get_close_matches(q, questions, n=1, cutoff=0.55)
    if not matches:
        return None
    for stored_q, answer in FAQS:
        if stored_q == matches[0]:
            return answer
    return None


