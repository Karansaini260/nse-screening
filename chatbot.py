"""
Rule-based chatbot. No external API, no model download — every answer
is generated by pattern-matching the user's question against a small
set of intents and pulling the answer from the live app state.

The bot is intentionally small but useful. Recognised intents:

  * "what is X" / "explain X"  -> glossary lookup (SMMA, ETQ, LTQ, ...)
  * "show Y" / "price Y" / "LTP Y" -> pulls LTP, SMMA(20), SMMA(120)
                                       for a Nifty 100 symbol
  * "top movers" / "best X"     -> ranks the universe by SMMA gap or
                                    LTQ acceleration
  * "open positions" / "my trades" -> lists currently-open trades
  * "help" / "what can you do"  -> returns a usage tip list
  * anything else               -> fuzzy match against the FAQ, or
                                    "I don't know" if nothing matches

The bot has no memory across turns — each call is stateless. That's
fine for a screener assistant and avoids building a session store.
"""

