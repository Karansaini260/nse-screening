HELP_TEXT = (
    "I can help with:\n"
    "  • Definitions — try 'what is smma' or 'explain etq'\n"
    "  • Symbol lookup — 'price reliance', 'ltp tcs', 'show infosys'\n"
    "  • Top movers — 'top 5 by smma gap', 'best by ltq acceleration'\n"
    "  • Your open positions — 'open trades', 'my positions'\n"
    "  • Recent signals — 'recent signals', 'latest crossovers'\n"
    "  • General help — 'help'"
)


def _format_symbol_state(sym: str) -> str:
    st = wsc.states.get(sym)
    if st is None or st.ltp == 0:
        return f"I don't have any data for {sym} yet. The feed may still be warming up."
    parts = [f"{sym}  LTP ₹{st.ltp:.2f}"]
    if st.smma20:
        parts.append(f"  SMMA20 ₹{st.smma20:.2f}")
    if st.smma120:
        parts.append(f"  SMMA120 ₹{st.smma120:.2f}")
    if st.bid_qty:
        parts.append(f"\nBid ₹{st.bid_price:.2f} × {st.bid_qty:,}    "
                     f"Ask ₹{st.ask_price:.2f} × {st.ask_qty:,}")
    parts.append(f"\nETQ 5m={st.get_etq(5):,}  20m={st.get_etq(20):,}  60m={st.get_etq(60):,}")
    return "".join(parts)


def _format_open_positions() -> str:
    opens = open_trades_snapshot()
    if not opens:
        return "You have no open positions right now."
    lines = [f"Open positions ({len(opens)}):"]
    for sym, t in opens.items():
        lines.append(
            f"  • {sym:12} {t['direction']:4} entry ₹{t['entry_price']:.2f}  "
            f"@ {t['entry_time'].strftime('%H:%M:%S')}"
        )
    return "\n".join(lines)


def _format_recent_signals(n: int = 5) -> str:
    recs = signals.all()[-n:]
    if not recs:
        return "No crossovers have fired yet."
    lines = [f"Recent {len(recs)} crossovers:"]
    for r in reversed(recs):
        lines.append(
            f"  • {r.when.strftime('%H:%M:%S')}  {r.symbol:12} {r.direction:4} "
            f"LTP ₹{r.ltp:.2f}  {r.decision} (p={r.probability:.2f})"
        )
    return "\n".join(lines)


def _rank_by_something(rank_key: str, top_n: int = 5) -> str:
    """Sort the universe by `rank_key` and return the top N."""
    rows = []
    for sym, st in wsc.states.items():
        if st.ltp == 0 or not st.smma20 or not st.smma120:
            continue
        f = st.get_features()
        if rank_key == "smma_gap":
            score = f["smma_gap_pct"]
            label = "SMMA gap %"
        elif rank_key == "ltq_accel":
            score = f["ltq_ratio_2m_5m"]
            label = "LTQ 2m/5m ratio"
        elif rank_key == "imbalance":
            score = f["bid_ask_imbalance"]
            label = "bid-ask imbalance"
        else:
            return f"Unknown ranking: {rank_key}"
        rows.append((score, sym, st.ltp))
    if not rows:
        return "Not enough data yet to rank."
    rows.sort(key=lambda r: r[0], reverse=True)
    lines = [f"Top {min(top_n, len(rows))} by {label}:"]
    for score, sym, ltp in rows[:top_n]:
        lines.append(f"  • {sym:12} {score:+.4f}   LTP ₹{ltp:.2f}")
    return "\n".join(lines)


def _parse_top_n(text: str, default: int = 5) -> int:
    m = re.search(r"\b(?:top\s+)?(\d{1,2})\b", text)
    if m:
        n = int(m.group(1))
        return max(1, min(20, n))
    return default


def respond(question: str) -> str:
    """
    Main entry point. Takes the raw user question and returns a string
    answer. Pure function — no Tk dependency, easy to unit-test.
    """
    q = _norm(question)
    if not q:
        return "Type a question or 'help' to see what I can do."

    # Help
    if q in ("help", "?", "what can you do", "commands"):
        return HELP_TEXT

    # Recent signals
    if any(k in q for k in ("recent signal", "latest signal", "latest cross", "recent cross")):
        return _format_recent_signals(_parse_top_n(q, default=5))

    # Open positions
    if any(k in q for k in ("open position", "open trade", "my position", "my trade", "position")):
        return _format_open_positions()

    # Top rankings
    if any(k in q for k in ("top", "best", "rank", "mover", "biggest")):
        if "imbalance" in q or "bid" in q or "ask" in q:
            return _rank_by_something("imbalance", _parse_top_n(q))
        if "ltq" in q:
            return _rank_by_something("ltq_accel", _parse_top_n(q))
        if "smma" in q or "gap" in q:
            return _rank_by_something("smma_gap", _parse_top_n(q))
        # default: SMMA gap
        return _rank_by_something("smma_gap", _parse_top_n(q))

    # Symbol lookup
    sym = _find_symbol(question)
    if sym is not None and any(k in q for k in (
        "show", "price", "ltp", "quote", "tell me about", "what about", "how is", "status",
    )):
        return _format_symbol_state(sym)

    # Glossary: "what is X" / "explain X" / "define X"
    for prefix in ("what is ", "what's ", "explain ", "define ", "meaning of ", "meaning "):
        if q.startswith(prefix):
            term = q[len(prefix):].strip(" ?.,")
            ans = _glossary(term)
            if ans:
                return ans
            return f"I don't have a definition for '{term}'. Try 'help' for what I can do."

    # "X meaning" or just "X" — try glossary directly
    if sym is None:
        # maybe they typed just a term like "smma" or "etq"
        direct = _glossary(q)
        if direct:
            return direct
        # Single-word question about a known glossary term with no prefix
        for key in GLOSSARY:
            if key in q.split():
                return GLOSSARY[key]

    # Last resort: fuzzy FAQ match
    faq = _fuzzy_faq(q)
    if faq:
        return faq

    return (
        "I'm not sure how to answer that. Try:\n"
        "  • 'help' to see what I can do\n"
        "  • 'price RELIANCE' for a symbol quote\n"
        "  • 'top 5 by smma gap' for the leaderboard\n"
        "  • 'open positions' for your current trades"
    )
